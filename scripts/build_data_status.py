#!/usr/bin/env python3
"""Create a public data-freshness manifest for the static site."""
from __future__ import annotations

import json
import os
import re
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "site" / "data"


def assignment(path: Path, name: str, default):
    if not path.exists():
        return default
    source = path.read_text(encoding="utf-8")
    match = re.search(rf"window\.{re.escape(name)}\s*=\s*(.*?);", source, re.S)
    if not match:
        return default
    try:
        return json.loads(match.group(1))
    except (json.JSONDecodeError, TypeError):
        return default


profiles = assignment(DATA / "profiles.js", "COMPANY_PROFILES", {})
profiles_updated = assignment(DATA / "profiles.js", "COMPANY_PROFILES_UPDATED", "")
financials = assignment(DATA / "financials.js", "COMPANY_FINANCIALS", [])
financials_meta = assignment(DATA / "financials.js", "COMPANY_FINANCIALS_META", {})
peers = assignment(DATA / "peers.js", "PEERS", {})
market = assignment(DATA / "market.js", "MARKET", {})


def source(label: str, updated, count, outcome: str):
    updated = str(updated or "")
    if not updated:
        status, note = "missing", "기준일 확인 불가"
    elif outcome == "success":
        status, note = "fresh", "이번 배포에서 수집 성공"
    elif outcome == "failure":
        status, note = "cached", "이번 수집 실패 · 이전 데이터 유지"
    else:
        status, note = "cached", "저장된 수집 데이터 사용"
    return {"label": label, "updated": updated, "count": count if isinstance(count, int) else None, "status": status, "note": note}


manifest = {
    "generatedAt": datetime.now(ZoneInfo("Asia/Seoul")).strftime("%Y-%m-%d %H:%M KST"),
    "sources": {
        "profiles": source("DART 기업정보", profiles_updated, len(profiles) if isinstance(profiles, dict) else None, os.getenv("PROFILE_OUTCOME", "")),
        "financials": source("DART 재무", financials_meta.get("updated") if isinstance(financials_meta, dict) else "", len(financials) if isinstance(financials, list) else None, os.getenv("FINANCIALS_OUTCOME", "")),
        "peers": source("해외 기업", peers.get("updated") if isinstance(peers, dict) else "", len(peers.get("list", [])) if isinstance(peers, dict) and isinstance(peers.get("list"), list) else None, os.getenv("PEERS_OUTCOME", "")),
        "market": source("국내 시세", market.get("updated") if isinstance(market, dict) else "", len(market.get("list", [])) if isinstance(market, dict) and isinstance(market.get("list"), list) else None, os.getenv("MARKET_OUTCOME", "")),
    },
}
(DATA / "status.js").write_text(
    "/* Generated by scripts/build_data_status.py. Do not edit by hand. */\n"
    "window.SITE_DATA_STATUS = " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(json.dumps(manifest, ensure_ascii=False))
