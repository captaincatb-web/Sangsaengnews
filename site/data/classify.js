// 소재·부품·장비 구분과 매출 규모 구간. 대시보드와 경영 현황 보고가 함께 쓴다.
// 1) segments.js 에 직접 분류한 기업 → 확정
// 2) 회사 이름(외국계 한국법인처럼 업종코드가 '도매'로 잡히는 곳) → 추정
// 3) DART 업종코드(KSIC) → 추정, 나머지는 미분류
(() => {
  const NAME_RULES = [
    ["장비", /램리서치|도쿄일렉트론|에이에스엠엘|어플라이드머티|케이엘에이|히타치하이테크|니콘|캐논|레이저텍|노바메저링|온투이노베이션|브룩스|엠케이에스|인피콘|호리바|기가포톤|에바라|아드반테스트|알박|에드워드|파이퍼베큠|일신이온|가스트론|씨티피|에이에스엠케이/],
    ["소재", /린데|에어프로덕츠|에어리퀴드|매슨|디아이지에어|이와타니|메티슨|에어퍼스트|바스프|신에츠|후지필름|제이에스알|토소|칸토덴카|미쓰이화학|다이킨|레조낙|헨켈|아토텍|디디피|이시하라|스미세이|스미베|세키스이|린텍|대일본인쇄|후루야|제이엑스금속|고려아연|엘티메탈|엘에스엠앤엠|케미칼|화학|머티리얼|머트리얼|소재|가스|실트론|웨이퍼/],
    ["부품", /인테그리스|그린트위드|발카|쿠어스텍|메르센|무라타|교세라|태양유전|티디케이|로옴|파나소닉|암페놀|몰렉스|센싸타|후지킨|쿼츠|세라믹|다이아몬드|프로브|소켓|히터/],
  ];
  // 업종코드 앞자리 → 구분 (긴 것부터 비교)
  const KSIC_RULES = [
    ["2927", "장비"], ["29", "장비"], ["27", "장비"],                 // 특수목적기계, 측정·검사기기
    ["2611", "소재"], ["20", "소재"], ["21", "소재"], ["22", "소재"], ["24", "소재"],
    ["23", "부품"], ["25", "부품"], ["26", "부품"], ["28", "부품"], ["30", "부품"],
  ];
  window.classifyCompany = (rec, segs) => {
    const seg = segs && segs[rec.c];
    if (seg) return { kind: seg[0], sub: seg[1], est: false };
    const byName = NAME_RULES.find(([, re]) => re.test(rec.n || ""));
    if (byName) return { kind: byName[0], sub: "", est: true };
    const ind = rec.ind || "";
    const byCode = KSIC_RULES.find(([p]) => ind.startsWith(p));
    return byCode ? { kind: byCode[1], sub: "", est: true } : { kind: "미분류", sub: "", est: false };
  };
  // 법적 기업규모가 입력되기 전까지 쓰는 매출 규모 구간(억원)
  window.SIZE_TIERS = ["1조 이상", "5천억~1조", "5천억 미만"];
  window.sizeTier = (sales) => (sales >= 10000 ? "1조 이상" : sales >= 5000 ? "5천억~1조" : "5천억 미만");
})();
